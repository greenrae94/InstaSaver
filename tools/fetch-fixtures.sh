#!/usr/bin/env bash
# Fetches the real Instagram pages the parser tests run against, using the post URLs
# in fixtures.properties (gitignored; create it from fixtures.properties.example).
# Writes reel.html, image-post.html, carousel.html and expectations.properties into
# app/src/test/resources/fixtures/.
#
# Headers must match app/src/main/java/com/raegreen/instasaver/InstagramHeaders.kt exactly —
# if that file changes, update this script too.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONFIG="$ROOT/fixtures.properties"
OUT="$ROOT/app/src/test/resources/fixtures"
USER_AGENT="Mozilla/5.0 (Linux; Android 15; SM-S938B) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/152.0.0.0 Mobile Safari/537.36"

if [[ ! -f "$CONFIG" ]]; then
  echo "fixtures.properties not found." >&2
  echo "Create it with:  cp fixtures.properties.example fixtures.properties" >&2
  echo "then fill in your own public post URLs and the values to assert, and re-run this script." >&2
  exit 1
fi

# Reads a key from fixtures.properties (first match; value is everything after the first '=').
prop() {
  grep -E "^$1[[:space:]]*=" "$CONFIG" | head -n1 | sed -E 's/^[^=]*=[[:space:]]*//; s/[[:space:]]+$//'
}

# Fetches a URL into a file, echoing the HTTP status (or "000" on a network failure).
fetch() {
  curl -sS -L --compressed -o "$2" -w '%{http_code}' --max-time 30 \
    -A "$USER_AGENT" \
    -H "Accept: text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,image/apng,*/*;q=0.8" \
    -H "Accept-Language: en-GB,en;q=0.9" \
    -H 'sec-ch-ua: "Chromium";v="152", "Google Chrome";v="152", "Not)A;Brand";v="99"' \
    -H "sec-ch-ua-mobile: ?1" -H 'sec-ch-ua-platform: "Android"' \
    -H "sec-fetch-dest: document" -H "sec-fetch-mode: navigate" -H "sec-fetch-site: none" -H "sec-fetch-user: ?1" \
    -H "upgrade-insecure-requests: 1" \
    "$1" 2>/dev/null
}

mkdir -p "$OUT"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# slot name -> output file
SLOTS=("reel:reel.html" "image:image-post.html" "carousel:carousel.html")

# Validate config and fetch everything into TMP first, so a failure never leaves a half-updated set.
for entry in "${SLOTS[@]}"; do
  slot="${entry%%:*}"
  file="${entry##*:}"
  url="$(prop "$slot.url")"

  for key in url username shortcode; do
    if [[ -z "$(prop "$slot.$key")" ]]; then
      echo "fixtures.properties is missing $slot.$key (see fixtures.properties.example)." >&2
      exit 1
    fi
  done

  if [[ "$slot" == "carousel" && -z "$(prop carousel.itemCount)" ]]; then
    echo "fixtures.properties is missing carousel.itemCount (see fixtures.properties.example)." >&2
    exit 1
  fi

  # ?l=1 is required: without it Instagram returns a page with no post data.
  case "$url" in
    *\?*) fetch_url="${url}&l=1" ;;
    *) fetch_url="${url%/}/?l=1" ;;
  esac

  echo "Fetching $slot: $url"
  code="$(fetch "$fetch_url" "$TMP/$file")"

  if [[ "$code" != "200" ]]; then
    echo "FAILED: $slot returned HTTP $code (or there is no network). Existing fixtures left untouched." >&2
    exit 1
  fi

  if ! grep -q xig_polaris_media "$TMP/$file"; then
    echo "FAILED: $slot page contains no xig_polaris_media post data." >&2
    echo "The post may be age-restricted, private or deleted, or Instagram changed its page format." >&2
    echo "Try a different public post for the '$slot' slot. Existing fixtures left untouched." >&2
    exit 1
  fi
done

# Everything fetched and verified: install the pages and write the expectations.
for entry in "${SLOTS[@]}"; do
  file="${entry##*:}"
  cp "$TMP/$file" "$OUT/$file"
done

{
  echo "# Generated by tools/fetch-fixtures.sh from fixtures.properties. Do not edit or commit."
  for slot in reel image carousel; do
    echo "$slot.username=$(prop "$slot.username")"
    echo "$slot.shortcode=$(prop "$slot.shortcode")"
  done
  echo "carousel.itemCount=$(prop carousel.itemCount)"
} > "$OUT/expectations.properties"

echo "Done. Wrote reel.html, image-post.html, carousel.html and expectations.properties to ${OUT#$ROOT/}/"
